impl Strings {
    pub fn mode_label(&self, id: &str) -> &'static str {
        match id {
            "eco" => self.mode_eco,
            "balanced" => self.mode_balanced,
            "performance" => self.mode_performance,
            "max" => self.mode_max,
            _ => self.mode_balanced,
        }
    }

    pub fn battery_status<'a>(&'a self, raw: &'a str) -> &'a str {
        match raw {
            "Charging" => self.bat_charging,
            "Discharging" => self.bat_discharging,
            "Not charging" => self.bat_not_charging,
            "Full" => self.bat_full,
            other => other,
        }
    }
}

